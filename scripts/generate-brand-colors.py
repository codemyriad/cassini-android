#!/usr/bin/env python3
"""Generate Android's canonical colour values from the checksum-pinned UX token file."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = Path('third_party/cassini-ux')
OUTPUT = Path('ui/src/main/kotlin/io/codemyriad/cassini/ui/theme/BrandTokenValues.kt')
TEMPORARY = Path('scripts/brand/temporary-old-palette.json')
RECORDING_ROLES = {
    'bg': 'ground', 'text': 'ink', 'text2': 'ink-2', 'line': 'line', 'barIdle': 'ink-3',
    'barFresh': 'record-ink', 'dot': 'record-ink', 'status': 'record-ink',
    'pauseFill': 'ink', 'onPause': 'ground', 'finish': 'record',
}
STATUSES = {'decided', 'placeholder', 'proposed', 'pending'}


def tokens(root):
    pin = json.loads((root / VENDOR / 'UPSTREAM.json').read_text())
    record = pin['files']['brand/tokens.json']
    commit = record.get('commit', pin['commit'])
    if record['source'] != 'brand/tokens.json' or not re.fullmatch(r'[0-9a-f]{40}', commit):
        raise ValueError('Invalid brand source or commit pin')
    raw = (root / VENDOR / 'brand/tokens.json').read_bytes()
    if hashlib.sha256(raw).hexdigest() != record['sha256']:
        raise ValueError('Vendored brand/tokens.json differs from its pinned SHA-256')
    document = json.loads(raw)
    if document['schema'] != 'cassini-ux/brand-tokens@1':
        raise ValueError('Unknown token schema')
    roles = document['tokens'] | document.get('derived', {})
    accepted = {}
    for name, role in roles.items():
        if role['status'] not in STATUSES:
            raise ValueError(f'Unknown status for {name}: {role["status"]}')
        if role['status'] in {'decided', 'placeholder'}:
            for mode in ('light', 'dark'):
                if not re.fullmatch(r'#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?', role[mode]):
                    raise ValueError(f'Invalid colour for {name}/{mode}')
            accepted[name] = role
    return commit, accepted


def temporary_palette(root):
    path = root / TEMPORARY
    checksum = path.with_suffix('.sha256')
    if not path.exists():
        if checksum.exists():
            raise ValueError('Remove the temporary palette checksum together with its snapshot')
        return None
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != checksum.read_text().strip():
        raise ValueError('Temporary old-palette snapshot differs from its frozen SHA-256')
    value = json.loads(raw)
    if value['schema'] != 'cassini-android/temporary-w1-palette@1' or value['removeIn'] != '#196':
        raise ValueError('Invalid temporary compatibility snapshot')
    return value


def color(value):
    if isinstance(value, list):
        return 'SpeakerColors(' + ', '.join(color(item) for item in value) + ')'
    if isinstance(value, dict):
        return color(value['hex']) + f".copy(alpha = {value['alpha']}f)"
    if not re.fullmatch(r'#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?', value):
        raise ValueError(f'Invalid snapshot colour: {value}')
    rgba = value[1:].upper()
    argb = rgba[-2:] + rgba[:6] if len(rgba) == 8 else 'FF' + rgba
    return f'Color(0x{argb})'



def generated(root):
    commit, roles = tokens(root)
    lines = [f'// Generated by scripts/generate-brand-colors.py from cassini-ux {commit}; do not edit.',
             '@file:Suppress("MagicNumber")', '', 'package io.codemyriad.cassini.ui.theme', '',
             'import androidx.compose.ui.graphics.Color', '', 'internal object BrandTokenValues {']
    for mode in ('light', 'dark'):
        lines.append(f'    val {mode}: Map<String, Color> = mapOf(')
        for name, role in roles.items():
            rgba = role[mode][1:].upper()
            argb = rgba[-2:] + rgba[:6] if len(rgba) == 8 else 'FF' + rgba
            lines.append(f'        "{name}" to Color(0x{argb}),')
        lines.append('    )')
    snapshot = temporary_palette(root)
    mask = color(snapshot['iconMask']) if snapshot else 'light.getValue("ink")'
    lines.append(f'    val iconMask: Color = {mask}')
    lines.append('}')
    # Constructor defaults must not initialize ColorKt while these legacy values are still being assigned.
    lines += ['', 'internal fun canvasValue(dark: Boolean, role: String): Color =',
              '    (if (dark) BrandTokenValues.dark else BrandTokenValues.light).getValue(role)']
    if snapshot:
        lines += ['', '// TEMPORARY: coordinator-approved no-pixel-change bridge for #195. Delete in #196.',
                  '// Generated from scripts/brand/temporary-old-palette.json; never edit these values here.']
        for mode in ('light', 'dark'):
            lines += ['', f'internal val Legacy{mode.title()}Colors: CassiniColors = CassiniColors(',
                      f'    isDark = {str(mode == "dark").lower()},']
            lines += [f'    {name} = {color(value)},' for name, value in snapshot[mode].items()]
            lines.append(')')
    lines += ['', 'val CassiniRecordingColors: RecordingColors = RecordingColors(']
    for name, role in RECORDING_ROLES.items():
        value = color(snapshot['recording'][name]) if snapshot else f'BrandTokenValues.dark.getValue("{role}")'
        lines.append(f'    {name} = {value},')
    lines.append(')')
    return '\n'.join(lines) + '\n'


def generated_files(root):
    yield OUTPUT, generated(root)
    snapshot = temporary_palette(root)
    _, roles = tokens(root)
    for mode, qualifier in [('light', 'values'), ('dark', 'values-night')]:
        if snapshot:
            values = dict(snapshot['xml'][mode])
        else:
            values = {'ui_window_bg': roles['ground'][mode], 'ui_logo_ink': roles['ink'][mode]}
            if mode == 'light':
                values.update(ui_launcher_background=roles['ground']['light'], ui_launcher_ink=roles['ink']['light'])
        if mode == 'light':
            values['ui_brand_on_record'] = roles['on-record']['light']
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 '<!-- Generated by scripts/generate-brand-colors.py; do not edit. -->']
        if snapshot:
            lines.append('<!-- TEMPORARY old palette for #195; #196 deletes the compatibility snapshot. -->')
        lines.append('<resources xmlns:tools="http://schemas.android.com/tools">')
        for name, value in values.items():
            unused = ' tools:ignore="UnusedResources"' if name == 'ui_logo_ink' else ''
            lines.append(f'    <color name="{name}"{unused}>{value}</color>')
        lines.append('</resources>')
        yield Path(f'ui/src/main/res/{qualifier}/colors.xml'), '\n'.join(lines) + '\n'



def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, source in generated_files(ROOT):
        target = ROOT / path
        if args.check:
            if not target.exists() or target.read_text() != source:
                raise SystemExit(f'Stale generated brand colours: {path}; run scripts/generate-brand-colors.py')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(source)


if __name__ == '__main__':
    main()
